macro_rules! make_consts {
    // There are no more attributes to match:
    // build the actual const definition string literal
    ([$([$attr:meta])*][] $error:ident $win32:expr) => {
        concat!(
            $("    #[", stringify!($attr), "]\n",)*
            "    pub const ", stringify!($error), ": Self = Self(unsafe {\n",
            "        ::core::num::NonZeroU32::new_unchecked(\n",
            "            ::windows_sys::Win32::Foundation::", $win32, "\n",
            "        )\n",
            "    });\n"
        )
    };
    // Match the custom attribute #[win_error = ...]:
    // take the default windows_sys error const and replace it with the given one
    ([$($attrs:tt)*][[win32_error = $win32:ident] $($others:tt)*] $error:ident $_:expr) => {
        make_consts!{[$($attrs)*][$($others)*] $error stringify!($win32)}
    };
    // Matched an unknown attributed:
    // place it on the matched list and go on
    ([$($attrs:tt)*][$attr:tt $($others:tt)*] $error:ident $win32:expr) => {
        make_consts!{[$($attrs)* $attr][$($others)*] $error $win32}
    };
    // Entry point with a rust-like syntax:
    // attributes will be matched one-by-one to find custom ones
    // the first [...] block contains the matched attributes, while the second contains the attributes to match
    // the windows_sys error const is, by default, defined by prefixing the given $error:ident with ERROR_
    ($( $( # $attrs:tt )* $error:ident ),* $(,)?) => {
        concat!("impl Error {\n", $(
            make_consts!{[][$($attrs)*] $error concat!("ERROR_", stringify!($error))},
        )* "}\n")
    };
}

